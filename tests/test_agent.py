def test_lookup_status_and_closure_flow(c):
    say(c, INTAKE)
    assert "NEW" in say(c, "show REF-2026-0001")["message"]
    assert say(c, "move REF-2026-0001 to in review")["outcome"] == "OK"
    assert say(c, "close REF-2026-0001 now")["route"] == "CLOSURE_APPROVAL"
    r = say(c, "request closure for REF-2026-0001")
    assert "approval #1" in r["message"]
    # the agent never approves: reviewer gets a confirmation request, nothing changes
    a = say(c, "approve approval #1", h=REV)
    assert a["outcome"] == "NEEDS_HUMAN_CONFIRMATION" and a["pending_confirmation"]["approval_id"] == 1
    assert c.get("/api/v1/reports/REF-2026-0001", headers=OP).json()["status"] == "IN_REVIEW"
    assert say(c, "approve approval #1", h=AGENT)["outcome"] == "REJECTED"
    assert say(c, "approve approval #1", h=OP)["outcome"] == "REJECTED"
    assert c.post("/api/v1/closure-requests/1/approve", json={}, headers=REV).status_code == 200  # human path
    assert say(c, "verify the audit chain")["message"].startswith("✅")


