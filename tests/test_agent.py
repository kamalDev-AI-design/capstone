def say(c, msg, h=OP):
    r = c.post("/api/v1/agent/messages", json={"message": msg}, headers=h)
    assert r.status_code == 200, r.text
    return r.json()


# ---------------------------------------------------------------- deterministic routing
@pytest.mark.parametrize("msg,expected", [
    ("hello", Route.DIRECT_RESPONSE),
    (INTAKE, Route.NEW_INTAKE),
    ("show REF-2026-0001", Route.REPORT_LOOKUP),
    ("REF-2026-0001", Route.REPORT_LOOKUP),
    ("list new reports", Route.REPORT_LOOKUP),
    ("verify the audit chain", Route.REPORT_LOOKUP),
    ("move REF-2026-0001 to in review", Route.STATUS_UPDATE),
    ("request closure for REF-2026-0001", Route.CLOSURE_APPROVAL),
    ("approve approval #3", Route.CLOSURE_APPROVAL),
    ("What does the SOP say about acknowledgement?", Route.SOP_LOOKUP),
    ("similar complaints about cracked seals", Route.HYBRID_KNOWLEDGE_LOOKUP),
    ("LOT-88392", Route.HYBRID_KNOWLEDGE_LOOKUP),
])
def test_routing_is_deterministic(msg, expected):
    r, ambiguous = route(msg, extract(msg))
    assert r == expected and not ambiguous
    assert route(msg, extract(msg)) == (r, ambiguous)


def test_classifier_only_for_ambiguous_and_never_mutating(c):
    calls = []
    svc = c.app.state.svc
    orch = AgentOrchestrator(svc, svc.agent.uow, classifier=lambda m: calls.append(m) or "NEW_INTAKE")
    actor = Actor("operator.demo", "INTAKE_OPERATOR")
    orch.run("show REF-2026-0001", actor, "r1")                 # deterministic -> classifier not consulted
    assert calls == []
    r = orch.run("zebra giraffe", actor, "r2")                  # ambiguous -> consulted, mutating route refused
    assert calls == ["zebra giraffe"] and r.route == Route.HYBRID_KNOWLEDGE_LOOKUP.value


