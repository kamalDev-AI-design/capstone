# ---------------------------------------------------------------- circuit breaker
class Stubborn:
    def __init__(self, call):
        self.call, self.n = call, 0

    def next_call(self, mem):
        self.n += 1
        return self.call


def test_circuit_breaker_halts_on_third_identical_invalid_call(c):
    svc = c.app.state.svc
    actor = Actor("operator.demo", "INTAKE_OPERATOR")
    p = Stubborn({"tool": "get_report", "arguments": {"reference_id": "BAD"}})
    r = svc.agent.run("show REF-2026-0001", actor, "cb1", proposer=p)
    assert r.outcome == "CIRCUIT_BREAKER_TRIGGERED" and r.circuit_breaker and p.n == 3     # 2 allowed, 3rd halts
    assert [t["status"] for t in r.tool_calls] == ["FAILED"] * 3
    ev = c.get("/api/v1/audit/events?limit=10", headers=OP).json()["items"]
    assert any(e["action_type"] == "CIRCUIT_BREAKER_TRIGGERED" for e in ev)
    # unknown tools are invalid too; different arguments produce different signatures
    p2 = Stubborn({"tool": "drop_database", "arguments": {}})
    assert svc.agent.run("show REF-2026-0001", actor, "cb2", proposer=p2).circuit_breaker
    seq = iter([{"tool": "get_report", "arguments": {"reference_id": f"BAD{i}"}} for i in range(6)])
    class Varied:
        def next_call(self, mem): return next(seq, None)
    assert not svc.agent.run("show REF-2026-0001", actor, "cb3", proposer=Varied()).circuit_breaker


def test_breaker_signature_canonical():
    a = signature("t", {"x": 1, "y": 2}, "e")
    assert a == signature("t", {"y": 2, "x": 1}, "e") != signature("t", {"x": 1, "y": 3}, "e")
    cb = CircuitBreaker({})
    assert [cb.register_invalid("t", {}, "e")[1] for _ in range(4)] == [False, False, True, True]


