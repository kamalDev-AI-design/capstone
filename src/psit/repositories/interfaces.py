"""Repository interfaces consumed by application services (no SQLAlchemy types)."""
from datetime import date, datetime
from typing import Protocol

from psit.domain.models import Approval, AuditEvent, Report, StatusHistoryEntry


class ReportRepository(Protocol):
    def next_reference_id(self, year: int) -> str: ...
    def add(self, *, reference_id: str, data: dict, created_by: str, now: datetime) -> Report: ...
    def get(self, reference_id: str) -> Report | None: ...
    def search(
        self, *, status: str | None, report_type: str | None, channel: str | None, product: str | None,
        date_from: date | None, date_to: date | None, limit: int, offset: int,
    ) -> tuple[list[Report], int]: ...
    def set_status(self, reference_id: str, status: str, now: datetime) -> Report: ...
    def stats(self) -> dict: ...


class HistoryRepository(Protocol):
    def add(self, *, reference_id: str, from_status: str | None, to_status: str, now: datetime,
            actor_id: str, actor_role: str, approval_id: int | None, request_id: str) -> None: ...
    def for_report(self, reference_id: str) -> list[StatusHistoryEntry]: ...


class ApprovalRepository(Protocol):
    def add_pending(self, *, reference_id: str, requested_by: str, now: datetime, version: int, note: str | None) -> Approval: ...
    def get(self, approval_id: int) -> Approval | None: ...
    def pending_for_report(self, reference_id: str) -> Approval | None: ...
    def list(self, status: str | None) -> list[Approval]: ...
    def mark_approved(self, approval_id: int, decided_by: str, now: datetime, note: str | None) -> Approval: ...


class AuditRepository(Protocol):
    def last_hash(self) -> str: ...
    def append(self, event: dict) -> AuditEvent: ...
    def list(self, *, entity_id: str | None, limit: int, offset: int) -> tuple[list[AuditEvent], int]: ...
    def all_ascending(self) -> list[AuditEvent]: ...
